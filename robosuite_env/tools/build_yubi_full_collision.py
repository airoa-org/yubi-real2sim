@dataclass(frozen=True)
class ObjGroup:
    name: str
    faces: tuple[tuple[int, int, int], ...]


@dataclass(frozen=True)
class GeneratedMesh:
    gid: str
    group: str
    mesh_name: str
    geom_name: str
    relative_file: str
    body_name: str
    content: str
    source_sha256: str
    source_hull_count: int
    source_hull_volume_m3: float
    proxy_volume_m3: float
    reduction: str


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _aggregate_hash(records: Iterable[tuple[str, str]]) -> str:
    digest = hashlib.sha256()
    for name, value in sorted(records):
        digest.update(name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(value.encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def _natural_key(value: str) -> tuple[object, ...]:
    return tuple(
        int(part) if part.isdigit() else part
        for part in re.split(r"(\d+)", value)
        if part
    )


def _fmt(value: float) -> str:
    if abs(value) < 5e-13:
        value = 0.0
    return f"{value:.9g}"


def _parse_face_index(token: str, vertex_count: int) -> int:
    raw = token.split("/", 1)[0]
    index = int(raw)
    if index < 0:
        index = vertex_count + 1 + index
    if index <= 0 or index > vertex_count:
        raise ValueError(f"OBJ face vertex index out of range: {token}")
    return index - 1


def read_obj(path: Path) -> tuple[np.ndarray, tuple[ObjGroup, ...]]:
    vertices: list[tuple[float, float, float]] = []
    groups: list[dict[str, object]] = []
    current: dict[str, object] | None = None

    def ensure_group() -> dict[str, object]:
        nonlocal current
        if current is None:
            current = {"name": "default", "faces": []}
            groups.append(current)
        return current

    with path.open("r", encoding="utf-8") as stream:
        for line in stream:
            if line.startswith("v "):
                values = line.split()
                if len(values) < 4:
                    raise ValueError(f"bad OBJ vertex in {path}: {line.rstrip()}")
                vertices.append(tuple(float(value) for value in values[1:4]))
            elif line.startswith("g "):
                group_name = line.split(maxsplit=1)[1].strip().split()[0]
                current = {"name": group_name or "default", "faces": []}
                groups.append(current)
            elif line.startswith("f "):
                refs = [
                    _parse_face_index(token, len(vertices))
                    for token in line.split()[1:]
                ]
                if len(refs) < 3:
                    continue
                faces = ensure_group()["faces"]
                assert isinstance(faces, list)
                for index in range(1, len(refs) - 1):
                    faces.append((refs[0], refs[index], refs[index + 1]))

    if not vertices:
        raise ValueError(f"OBJ has no vertices: {path}")
    parsed_groups = tuple(
        ObjGroup(str(group["name"]), tuple(group["faces"]))
        for group in groups
        if group["faces"]
    )
    if not parsed_groups:
        raise ValueError(f"OBJ has no face groups: {path}")
    return np.asarray(vertices, dtype=np.float64), parsed_groups


def _obj_text(
    name: str,
    vertices: np.ndarray,
    faces: Sequence[tuple[int, int, int]],
) -> str:
    first_seen: dict[int, int] = {}
    ordered: list[int] = []
    for face in faces:
        for index in face:
            if index not in first_seen:
                first_seen[index] = len(ordered) + 1
                ordered.append(index)
    lines = [f"o {name}\n", f"g {name}\n"]
    for index in ordered:
        x, y, z = vertices[index]
        lines.append(f"v {_fmt(x)} {_fmt(y)} {_fmt(z)}\n")
    for face in faces:
        lines.append("f " + " ".join(str(first_seen[index]) for index in face) + "\n")
    return "".join(lines)


def _convex_proxy(
    name: str,
    vertices: np.ndarray,
) -> tuple[str, float]:
    hull = ConvexHull(vertices)
    faces: list[tuple[int, int, int]] = []
    for simplex, equation in zip(hull.simplices, hull.equations):
        i0, i1, i2 = (int(value) for value in simplex)
        normal = np.cross(vertices[i1] - vertices[i0], vertices[i2] - vertices[i0])
        if float(np.dot(normal, equation[:3])) < 0.0:
            i1, i2 = i2, i1
        faces.append((i0, i1, i2))
    return _obj_text(name, vertices, faces), float(hull.volume)


def _group_vertex_ids(group: ObjGroup) -> np.ndarray:
    return np.unique(np.asarray(group.faces, dtype=np.int64).reshape(-1))


def _cluster_volume(vertices: np.ndarray, clusters: Sequence[Sequence[np.ndarray]]) -> float:
    result = 0.0
    for cluster in clusters:
        indices = np.unique(np.concatenate(cluster))
        result += float(ConvexHull(vertices[indices]).volume)
    return result


def _deterministic_kmeans_clusters(
    vertices: np.ndarray,
    group_ids: Sequence[np.ndarray],
    cluster_count: int,
) -> list[list[np.ndarray]]:
    centroids = np.asarray([vertices[indices].mean(axis=0) for indices in group_ids])
    first = min(range(len(centroids)), key=lambda index: tuple(centroids[index]))
    chosen = [first]
    while len(chosen) < cluster_count:
        distance = np.min(
            np.sum(
                (centroids[:, None, :] - centroids[chosen][None, :, :]) ** 2,
                axis=2,
            ),
            axis=1,
        )
        distance[chosen] = -1.0
        maximum = float(distance.max())
        candidates = np.flatnonzero(
            np.isclose(distance, maximum, rtol=0.0, atol=1e-18)
        )
        chosen.append(
            min(candidates.tolist(), key=lambda index: tuple(centroids[index]))
        )
    centers = centroids[chosen].copy()
    labels = np.full(len(centroids), -1, dtype=np.int64)
    for _ in range(100):
        distance = np.sum(
            (centroids[:, None, :] - centers[None, :, :]) ** 2,
            axis=2,
        )
        updated = np.argmin(distance, axis=1)
        for cluster_index in range(cluster_count):
            if np.any(updated == cluster_index):
                continue
            candidate = int(np.argmax(np.min(distance, axis=1)))
            updated[candidate] = cluster_index
        updated_centers = np.asarray(
            [
                centroids[updated == cluster_index].mean(axis=0)
                for cluster_index in range(cluster_count)
            ]
        )
        if np.array_equal(updated, labels) and np.allclose(
            updated_centers, centers, rtol=0.0, atol=1e-15
        ):
            break
        labels = updated
        centers = updated_centers
    return [
        [group_ids[index] for index in range(len(group_ids)) if labels[index] == label]
        for label in range(cluster_count)
    ]


def _axis_clusters(
    vertices: np.ndarray,
    group_ids: Sequence[np.ndarray],
    cluster_count: int,
) -> list[list[list[np.ndarray]]]:
    centroids = np.asarray([vertices[indices].mean(axis=0) for indices in group_ids])
    centered = centroids - centroids.mean(axis=0)
    _, _, principal_axes = np.linalg.svd(centered, full_matrices=False)
    axes = [*np.eye(3), *principal_axes]
    candidates: list[list[list[np.ndarray]]] = []
    for axis in axes:
        projection = centroids @ axis
        order = np.argsort(projection, kind="stable")
        count_bins = [indices for indices in np.array_split(order, cluster_count) if len(indices)]
        candidates.append(
            [[group_ids[int(index)] for index in indices] for indices in count_bins]
        )
        edges = np.linspace(
            float(projection.min()) - 1e-12,
            float(projection.max()) + 1e-12,
            cluster_count + 1,
        )
        range_bins = [
            np.flatnonzero(
                (projection >= edges[index]) & (projection < edges[index + 1])
            )
            for index in range(cluster_count)
        ]
        candidates.append(
            [
                [group_ids[int(index)] for index in indices]
                for indices in range_bins
                if len(indices)
            ]
        )
    return candidates


def _proxy_clusters(
    vertices: np.ndarray,
    groups: Sequence[ObjGroup],
    cluster_limit: int,
) -> tuple[list[list[np.ndarray]], float]:
    group_ids = [_group_vertex_ids(group) for group in groups]
    source_volume = sum(
        float(ConvexHull(vertices[indices]).volume) for indices in group_ids
    )
    if cluster_limit <= 1 or len(group_ids) == 1:
        return [[*group_ids]], source_volume
    cluster_count = min(cluster_limit, len(group_ids))
    candidates = [
        [[*group_ids]],
        _deterministic_kmeans_clusters(vertices, group_ids, cluster_count),
        *_axis_clusters(vertices, group_ids, cluster_count),
    ]
    best = min(
        candidates,
        key=lambda candidate: (
            _cluster_volume(vertices, candidate),
            len(candidate),
            tuple(len(cluster) for cluster in candidate),
        ),
    )
    return best, source_volume


def _load_parts(asset_dir: Path) -> list[dict[str, object]]:
    manifest_path = asset_dir / "manifest.json"
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    parts = payload.get("parts")
    if not isinstance(parts, list) or len(parts) != 60:
        raise RuntimeError(f"{asset_dir.name} manifest must contain 60 parts")
    counts = {
        group: sum(part.get("group") == group for part in parts)
        for group in EXPECTED_GROUP_COUNTS
    }
    if counts != EXPECTED_GROUP_COUNTS:
        raise RuntimeError(f"{asset_dir.name} group counts changed: {counts}")
    gids = [str(part.get("gid")) for part in parts]
    if len(gids) != len(set(gids)):
        raise RuntimeError(f"{asset_dir.name} manifest contains duplicate gids")
    return sorted(parts, key=lambda part: _natural_key(str(part["gid"])))


def _body_for_group(group: str) -> str:
    return {
        "body": "yubi_geom",
        "L_jaw": "finger_left",
        "R_jaw": "finger_right",
    }[group]


def _guard_records(
    asset_dir: Path,
    parts: Sequence[dict[str, object]],
) -> list[GeneratedMesh]:
    result: list[GeneratedMesh] = []
    for part in parts:
        gid = str(part["gid"])
        group = str(part["group"])
        if group != "body" and gid.endswith(EXACT_FINGER_SUFFIXES):
            continue
        source = asset_dir / "coll_mj" / f"{gid}.obj"
        if not source.is_file():
            raise FileNotFoundError(source)
        vertices, groups = read_obj(source)
        expected_hulls = int(part["collision_hulls"])
        if len(groups) != expected_hulls:
            raise RuntimeError(
                f"{asset_dir.name}/{gid}: manifest says {expected_hulls} hulls, "
                f"OBJ contains {len(groups)}"
            )
        source_digest = _sha256_file(source)
        body_name = _body_for_group(group)
        part_label = "body" if group == "body" else (
            "finger_left" if group == "L_jaw" else "finger_right"
        )
        suffix = gid.rsplit("__", 1)[-1]
        if group == "body":
            cluster_limit = BODY_PROXY_CLUSTER_LIMITS.get(gid, 1)
            clusters, source_volume = _proxy_clusters(
                vertices, groups, cluster_limit
            )
        else:
            cluster_limit = MOVING_PROXY_CLUSTER_LIMITS.get(suffix, 1)
            clusters, source_volume = _proxy_clusters(
                vertices, groups, cluster_limit
            )
        for cluster_index, cluster in enumerate(clusters):
            indices = np.unique(np.concatenate(cluster))
            if len(clusters) == 1:
                output_stem = f"{gid}_convex"
                geom_name = f"{GUARD_GEOM_PREFIX}{part_label}_{gid}"
            else:
                output_stem = f"{gid}_proxy_h{cluster_index:03d}"
                geom_name = (
                    f"{GUARD_GEOM_PREFIX}{part_label}_{gid}_h{cluster_index:03d}"
                )
            content, proxy_volume = _convex_proxy(output_stem, vertices[indices])
            result.append(
                GeneratedMesh(
                    gid=gid,
                    group=group,
                    mesh_name=f"{GUARD_MESH_PREFIX}{output_stem}",
                    geom_name=geom_name,
                    relative_file=(
                        f"{asset_dir.name}/{GUARD_DIRECTORY}/{output_stem}.obj"
                    ),
                    body_name=body_name,
                    content=content,
                    source_sha256=source_digest,
                    source_hull_count=expected_hulls,
                    source_hull_volume_m3=source_volume,
                    proxy_volume_m3=proxy_volume,
                    reduction=(
                        "one_conservative_convex_proxy"
                        if len(clusters) == 1
                        else "spatially_clustered_conservative_convex_proxies"
                    ),
                )
            )
    names = [record.mesh_name for record in result]
    files = [record.relative_file for record in result]
    if len(names) != len(set(names)) or len(files) != len(set(files)):
        raise RuntimeError(f"{asset_dir.name} generated guard outputs are not unique")
    return result


def _parse_xml(path: Path) -> ET.ElementTree:
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    return ET.parse(path, parser=parser)


def _remove_generated(root: ET.Element) -> None:
    asset = root.find("./asset")
    if asset is None:
        raise RuntimeError("YUBI MJCF has no asset section")
    asset[:] = [
        child
        for child in asset
        if not (
            child.tag == "mesh"
            and (child.get("name") or "").startswith(GUARD_MESH_PREFIX)
        )
    ]
    for parent in root.iter():
        parent[:] = [
            child
            for child in parent
            if not (
                child.tag == "geom"
                and (child.get("name") or "").startswith(GUARD_GEOM_PREFIX)
            )
        ]


def _unique_body(root: ET.Element, name: str) -> ET.Element:
    bodies = root.findall(f".//body[@name='{name}']")
    if len(bodies) != 1:
        raise RuntimeError(f"YUBI MJCF must contain one body {name!r}, got {len(bodies)}")
    return bodies[0]


def _visual_by_gid(root: ET.Element) -> dict[str, ET.Element]:
    asset = root.find("./asset")
    if asset is None:
        raise RuntimeError("YUBI MJCF has no asset section")
    mesh_files = {
        mesh.get("name", ""): mesh.get("file", "")
        for mesh in asset.findall("mesh")
    }
    result: dict[str, ET.Element] = {}
    for geom in root.iter("geom"):
        mesh = geom.get("mesh", "")
        if not mesh.startswith("v2_vis_"):
            continue
        gid = Path(mesh_files.get(mesh, "")).stem
        if not gid:
            raise RuntimeError(f"visual mesh asset {mesh!r} has no file")
        if gid in result:
            raise RuntimeError(f"visual gid {gid!r} appears more than once")
        if geom.get("contype") != "0" or geom.get("conaffinity") != "0":
            raise RuntimeError(f"visual gid {gid!r} is contact-enabled")
        result[gid] = geom
    return result


def _existing_collision_snapshot(root: ET.Element) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    for geom in root.iter("geom"):
        name = geom.get("name", "")
        if name.startswith(GUARD_GEOM_PREFIX):
            continue
        if "finger_" not in name or "_collision_" not in name:
            continue
        result[name] = dict(geom.attrib)
    return result


def _apply_records(root: ET.Element, records: Sequence[GeneratedMesh]) -> None:
    asset = root.find("./asset")
    assert asset is not None
    visuals = _visual_by_gid(root)
    bodies = {
        name: _unique_body(root, name)
        for name in ("yubi_geom", "finger_left", "finger_right")
    }
    for record in records:
        ET.SubElement(
            asset,
            "mesh",
            name=record.mesh_name,
            file=record.relative_file,
        )
    for record in records:
        visual = visuals.get(record.gid)
        if visual is None:
            raise RuntimeError(f"generated guard has no visual source: {record.gid}")
        attributes = {
            "name": record.geom_name,
            **GUARD_CONTACT,
        }
        for transform_name in ("pos", "quat", "euler", "axisangle", "xyaxes", "zaxis"):
            if visual.get(transform_name) is not None:
                attributes[transform_name] = str(visual.get(transform_name))
        attributes.update(type="mesh", mesh=record.mesh_name)
        ET.SubElement(bodies[record.body_name], "geom", attributes)


def _clear_xml_whitespace(root: ET.Element) -> None:
    for element in root.iter():
        if element.text is not None and not element.text.strip():
            element.text = None
        if element.tail is not None and not element.tail.strip():
            element.tail = None


def _xml_bytes(tree: ET.ElementTree) -> bytes:
    root = tree.getroot()
    _clear_xml_whitespace(root)
    ET.indent(tree, space="  ")
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n"


def _render_mjcf(path: Path, records: Sequence[GeneratedMesh]) -> tuple[bytes, int]:
    tree = _parse_xml(path)
    root = tree.getroot()
    _remove_generated(root)
    before = _existing_collision_snapshot(root)
    _apply_records(root, records)
    after = _existing_collision_snapshot(root)
    if before != after:
        raise RuntimeError(f"{path.name} existing finger collision geoms changed")
    collision_count = sum(
        geom.get("type") == "mesh"
        and int(geom.get("contype", "1")) != 0
        and int(geom.get("conaffinity", "1")) != 0
        for geom in root.iter("geom")
    )
    return _xml_bytes(tree), collision_count


def _atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(content)
    os.replace(temporary, path)


def _side_manifest(
    side: str,
    asset_dir: Path,
    mjcf: Path,
    records: Sequence[GeneratedMesh],
    collision_count: int,
) -> dict[str, object]:
    by_gid: dict[str, list[GeneratedMesh]] = {}
    for record in records:
        by_gid.setdefault(record.gid, []).append(record)
    part_records = []
    for gid in sorted(by_gid, key=_natural_key):
        outputs = by_gid[gid]
        output_hashes = [
            (Path(record.relative_file).name, _sha256_bytes(record.content.encode("utf-8")))
            for record in outputs
        ]
        part_records.append(
            {
                "gid": gid,
                "group": outputs[0].group,
                "reduction": outputs[0].reduction,
                "source": f"{asset_dir.name}/coll_mj/{gid}.obj",
                "source_sha256": outputs[0].source_sha256,
                "source_hull_count": outputs[0].source_hull_count,
                "source_hull_volume_m3": outputs[0].source_hull_volume_m3,
                "output_count": len(outputs),
                "proxy_volume_m3": sum(output.proxy_volume_m3 for output in outputs),
                "proxy_to_source_hull_volume_ratio": (
                    sum(output.proxy_volume_m3 for output in outputs)
                    / outputs[0].source_hull_volume_m3
                ),
                "output_aggregate_sha256": _aggregate_hash(output_hashes),
            }
        )
    output_hashes = [
        (record.relative_file, _sha256_bytes(record.content.encode("utf-8")))
        for record in records
    ]
    return {
        "side": side,
        "mjcf": mjcf.relative_to(REPO_ROOT).as_posix(),
        "source_manifest": f"robosuite_env/assets/{asset_dir.name}/manifest.json",
        "source_manifest_sha256": _sha256_file(asset_dir / "manifest.json"),
        "visual_parts": 60,
        "exact_finger_parts": 4,
        "added_visual_parts": 56,
        "fixed_body_convex_proxy_geoms": sum(record.group == "body" for record in records),
        "moving_finger_convex_proxy_geoms": sum(record.group != "body" for record in records),
        "generated_collision_geoms": len(records),
        "final_collision_geoms_including_mount": collision_count,
        "output_aggregate_sha256": _aggregate_hash(output_hashes),
        "parts": part_records,
    }


def _contract_manifest(sides: dict[str, dict[str, object]]) -> bytes:
    payload = {
        "schema_version": 1,
        "generator": GENERATOR_RELATIVE,
        "scope": "shared bilateral YUBI asset",
        "contact": GUARD_CONTACT,
        "grasp_corridor_validation": GRASP_CORRIDOR_VALIDATION,
        "coverage": {
            "default": "one conservative convex proxy per visual part",
            "phantom_fill_mitigation": (
                "2-8 deterministic spatial proxies for reviewed concave parts"
            ),
            "exact_geometry6_geometry7": "source CoACD hulls used unchanged",
        },
        "sides": sides,
    }
    return (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode("utf-8")


def _build(*, write: bool) -> None:
    side_reports: dict[str, dict[str, object]] = {}
    desired_files: dict[Path, bytes] = {}
    for side, config in SIDE_CONFIG.items():
        mjcf = Path(config["mjcf"])
        asset_dir = Path(config["asset_dir"])
        parts = _load_parts(asset_dir)
        records = _guard_records(asset_dir, parts)
        xml_content, collision_count = _render_mjcf(mjcf, records)
        desired_files[mjcf] = xml_content
        for record in records:
            destination = ASSET_ROOT / record.relative_file
            desired_files[destination] = record.content.encode("utf-8")
        side_reports[side] = _side_manifest(
            side,
            asset_dir,
            mjcf,
            records,
            collision_count,
        )

    contract_path = ASSET_ROOT / "yubi_guard_collision_manifest.json"
    desired_files[contract_path] = _contract_manifest(side_reports)
    expected_meshes = {
        path.resolve()
        for path in desired_files
        if path.suffix == ".obj" and path.parent.name == GUARD_DIRECTORY
    }
    stale_meshes: list[Path] = []
    for config in SIDE_CONFIG.values():
        guard_dir = Path(config["asset_dir"]) / GUARD_DIRECTORY
        if guard_dir.is_dir():
            stale_meshes.extend(
                path
                for path in guard_dir.glob("*.obj")
                if path.resolve() not in expected_meshes
            )
    mismatches = [
        path
        for path, content in desired_files.items()
        if not path.is_file() or path.read_bytes() != content
    ]
    if write:
        for path in sorted(stale_meshes):
            path.unlink()
        for path in sorted(mismatches):
            _atomic_write(path, desired_files[path])
        print(
            f"[yubi-full-collision] wrote {len(mismatches)} changed files, "
            f"removed {len(stale_meshes)} stale generated meshes; "
            f"right={side_reports['right']['final_collision_geoms_including_mount']} "
            f"left={side_reports['left']['final_collision_geoms_including_mount']}"
        )
        return
    if mismatches or stale_meshes:
        relative = [
            path.relative_to(REPO_ROOT).as_posix()
            for path in [*mismatches, *stale_meshes][:20]
        ]
        suffix = " ..." if len(mismatches) + len(stale_meshes) > len(relative) else ""
        raise SystemExit(
            "YUBI full-collision outputs are stale or missing: "
            + ", ".join(relative)
            + suffix
        )
    print(
        "[yubi-full-collision] check OK; "
        f"right={side_reports['right']['final_collision_geoms_including_mount']} "
        f"left={side_reports['left']['final_collision_geoms_including_mount']}"
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    _build(write=bool(args.write))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
