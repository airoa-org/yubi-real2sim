"""Build the shared bilateral YUBI exterior-collision contract.

The checked-in YUBI manifests already contain CoACD output for all 60 visual
parts.  Historically the runtime MJCF connected only geometry6/geometry7 on
each moving finger (the structural fingertip and high-friction pad).  This
builder keeps those reviewed collision geoms byte-for-byte in meaning and adds
coverage for the remaining 56 parts:

* every uncovered part gets a conservative convex proxy;
* reviewed concave housing/finger parts use 2--8 spatial proxy clusters.

The reviewed geometry6/geometry7 fingertip and pad remain per-hull, so their
manipulation surface is not re-convexified.  The bounded proxy set avoids the
roughly 1,200 collision geoms per hand that a literal all-hull expansion would
create.  Both handed MJCFs and their generated meshes are emitted from the same
constants and validation path.
"""

